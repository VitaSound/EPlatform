def load_notes(out: Path) -> dict:
    path = out / "gen_notes.yaml"
    if not path.exists():
        path = DEFAULT_OUT / "gen_notes.yaml"
    if not path.exists():
        return {}
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def stamp() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def extract_q_classes(path: Path) -> set[str]:
    if not path.exists():
        return set()
    return set(re.findall(r'"(Q[A-Za-z0-9]+)"', path.read_text(encoding="utf-8")))


def ui_class_counts() -> Counter[str]:
    counts: Counter[str] = Counter()
    if not QT_FORMS.exists():
        return counts
    for p in QT_FORMS.rglob("*.ui"):
        try:
            text = p.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        counts.update(re.findall(r'class="(Q[A-Za-z0-9]+)"', text))
    return counts


def parse_rust_enum_variants(path: Path, enum_name: str) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    m = re.search(rf"pub enum {re.escape(enum_name)}\s*\{{", text)
    if not m:
        raise SystemExit(f"enum {enum_name} not found in {path}")
    i = m.end()
    depth = 1
    body: list[str] = []
    while i < len(text) and depth:
        ch = text[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                break
        body.append(ch)
        i += 1
    # Tokenize variants: doc comments + name + optional {fields} or (tuple);
    pattern = re.compile(
        r"(?:(?P<docs>(?:\s*///[^\n]*\n)+))?\s*"
        r"(?P<name>[A-Z][A-Za-z0-9_]*)"
        r"(?P<rest>\s*(?:\{[^}]*\}|\([^;]*\))?\s*,?)",
        re.M,
    )
    variants: list[dict] = []
    seen: set[str] = set()
    for match in pattern.finditer("".join(body)):
        name = match.group("name")
        if name in seen:
            continue
        docs_raw = match.group("docs") or ""
        doc = " ".join(
            line.strip()[3:].strip() if line.strip().startswith("///") else ""
            for line in docs_raw.splitlines()
        ).strip()
        rest = match.group("rest") or ""
        fields: list[str] = []
        if "{" in rest:
            field_block = rest[rest.find("{") + 1 : rest.rfind("}")]
            for fl in field_block.splitlines():
                fl = re.sub(r"///.*", "", fl).strip().rstrip(",")
                if not fl or fl.startswith("//"):
                    continue
                fm = re.match(r"([a-zA-Z_][a-zA-Z0-9_]*)\s*:", fl)
                if fm:
                    fields.append(fm.group(1))
        elif "(" in rest:
            inner = rest[rest.find("(") + 1 : rest.rfind(")")].replace("\n", " ").strip()
            if inner:
                fields = [inner]
        seen.add(name)
        variants.append({"name": name, "doc": doc, "fields": fields})
    return variants


def parse_lua_methods(path: Path, prefix: str) -> list[dict]:
    lines = path.read_text(encoding="utf-8").splitlines()
    methods: list[dict] = []
    for i, line in enumerate(lines):
        m = re.match(rf"^function {re.escape(prefix)}:([A-Za-z0-9_]+)\((.*)\)\s*$", line)
        if not m:
            continue
        name, args = m.group(1), m.group(2).strip()
        docs: list[str] = []
        j = i - 1
        while j >= 0 and lines[j].strip().startswith("--"):
            docs.append(lines[j].strip()[2:].strip())
            j -= 1
        docs.reverse()
        methods.append({"name": name, "args": args, "doc": " ".join(docs).strip()})
    return methods


def parse_deflua(path: Path) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    methods: list[dict] = []
    for m in re.finditer(r"deflua\s+([a-zA-Z0-9_]+)\(([^)]*)\)", text):
        args = re.sub(r"\s+", " ", m.group(2)).replace(", state", "").strip().rstrip(",")
        methods.append({"name": m.group(1), "args": args})
    return methods


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    def esc(s: str) -> str:
        return (s or "").replace("|", "\\|").replace("\n", " ")

    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(esc(c) for c in row) + " |")
    return "\n".join(lines) + "\n"


def categorize(cls: str) -> str:
    if cls in LAYOUT:
        return "Layouts"
    if cls in CONTROLS:
        return "Controls"
    if cls in VIEWS:
        return "Item views"
    if cls in NAV:
        return "Navigation / split"
    if cls in SHELL:
        return "Shell / windows"
    return "Other / mentioned"


QUIET = False


def write(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(GEN_BANNER + body.rstrip() + "\n", encoding="utf-8")
    if QUIET:
        return
    try:
        rel = path.relative_to(ROOT)
    except ValueError:
        rel = path
    print(f"wrote {rel}")


def gen_widgets(out: Path, notes: dict) -> None:
    rs_classes = extract_q_classes(WIDGETS_RS) | extract_q_classes(SHELL_RS)
    counts = ui_class_counts()
    all_classes = sorted(rs_classes | set(counts))
    wnotes = notes.get("widgets") or {}
    preamble = (notes.get("widgets_preamble") or "").strip()
    by_cat: dict[str, list[str]] = defaultdict(list)
    for cls in all_classes:
        by_cat[categorize(cls)].append(cls)

    parts = [
        "# Supported Widgets",
        "",
        preamble,
        "",
        f"_Generated {stamp()}._",
        "",
        f"Классов в `.ui` дереве форм: **{len(counts)}** уникальных, "
        f"всего вхождений: **{sum(counts.values())}**.",
        "",
    ]
    for cat in (
        "Layouts",
        "Controls",
        "Item views",
        "Navigation / split",
        "Shell / windows",
        "Other / mentioned",
    ):
        classes = by_cat.get(cat) or []
        if not classes:
            continue
        parts.append(f"## {cat}")
        parts.append("")
        rows = []
        for cls in classes:
            n = counts.get(cls, 0)
            src = []
            if cls in rs_classes:
                src.append("rqt/app")
            if n:
                src.append(f".ui×{n}")
            rows.append([f"`{cls}`", ", ".join(src) or "—", wnotes.get(cls, "")])
        parts.append(md_table(["Класс", "Где виден", "Заметки"], rows))
        parts.append("")

    not_goal = notes.get("not_a_goal") or []
    if not_goal:
        parts.append("## Явно не цель (сейчас)")
        parts.append("")
        for item in not_goal:
            parts.append(f"- {item}")
        parts.append("")

    parts.extend(
        [
            "## Как пользоваться",
            "",
            "1. Класс есть в таблице и желательно в `.ui` галерее.",
            "2. Свойства/события — через [[Lua Form API]].",
            "3. Инженерный parity: "
            "[qt-parity-guide](https://github.com/VitaSound/EPlatform/blob/main/docs/qt-parity-guide.md).",
            "",
        ]
    )
    write(out / "Supported-Widgets.md", "\n".join(parts))


