def update_rendering_link(out: Path) -> None:
    path = out / "Rendering-Pipeline.md"
    if not path.exists() or "[[Paint Commands]]" in path.read_text(encoding="utf-8"):
        return
    text = path.read_text(encoding="utf-8")
    link = "Актуальный enum-справочник: [[Paint Commands]] (генерируется из кода).\n\n"
    if "## Что автор формы должен знать" in text:
        text = text.replace("## Что автор формы должен знать", link + "## Что автор формы должен знать")
        path.write_text(text, encoding="utf-8")
        print(f"updated {path.relative_to(ROOT)}")


