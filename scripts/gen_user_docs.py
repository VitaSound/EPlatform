def generate_all(out: Path) -> None:
    notes = load_notes(out)
    # Prefer canonical notes from repo docs/user when generating into temp
    if not (out / "gen_notes.yaml").exists() and (DEFAULT_OUT / "gen_notes.yaml").exists():
        notes = load_notes(DEFAULT_OUT)
    gen_widgets(out, notes)
    gen_lua_form(out, notes)
    gen_lua_app(out, notes)
    gen_host_api(out)
    gen_paint(out, notes)
    update_sidebar(out)
    update_rendering_link(out)
    update_readme(out)


def normalize_generated(text: str) -> str:
    text = re.sub(r"_Generated [^\n]*\n?", "", text)
    return text


def fingerprint(folder: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    for name in GENERATED_NAMES:
        p = folder / name
        raw = p.read_text(encoding="utf-8") if p.exists() else ""
        out[name] = hashlib.sha256(normalize_generated(raw).encode()).hexdigest()
    return out


def check_fresh(out: Path) -> int:
    global QUIET
    QUIET = True
    before = fingerprint(out)
    with tempfile.TemporaryDirectory() as tmp:
        tmp_out = Path(tmp) / "user"
        tmp_out.mkdir()
        for name in (
            "Home.md",
            "Quick-Start.md",
            "Architecture.md",
            "Rendering-Pipeline.md",
            "gen_notes.yaml",
        ):
            src = out / name
            if src.exists():
                shutil.copy2(src, tmp_out / name)
        # notes always from real tree if missing in out
        if not (tmp_out / "gen_notes.yaml").exists() and (DEFAULT_OUT / "gen_notes.yaml").exists():
            shutil.copy2(DEFAULT_OUT / "gen_notes.yaml", tmp_out / "gen_notes.yaml")
        generate_all(tmp_out)
        after = fingerprint(tmp_out)
    stale = [k for k in GENERATED_NAMES if before.get(k) != after.get(k)]
    if stale:
        print("generated docs are stale:", ", ".join(stale), file=sys.stderr)
        print("run: ./scripts/gen_user_docs.py && ./scripts/sync_wiki.sh", file=sys.stderr)
        return 1
    print("generated docs up to date")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if generated pages in docs/user are stale",
    )
    ap.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="output directory (default: docs/user)",
    )
    args = ap.parse_args()
    out = args.out.resolve()
    if args.check:
        return check_fresh(out)
    generate_all(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
